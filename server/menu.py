"""Menu file helpers: load `var MENU = {...};`, validate it and resolve which week applies to a date.

The format is documented in docs/domain-model.md. Kept dependency-light: json5 is used when
available (menu files written by hand may have comments or trailing commas), plain json otherwise."""
import datetime
import json
import re

try:
    import json5
except ImportError:  # pragma: no cover - json5 is a declared dependency, json is a fallback
    json5 = None

DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")


def parse_js_object(text):
    """Return the object literal assigned in a `var NAME = {...};` file."""
    start, end = text.index("{"), text.rindex("}")
    body = text[start:end + 1]
    return json5.loads(body) if json5 else json.loads(body)


def load_menu(path):
    with open(path, encoding="utf-8") as f:
        return parse_js_object(f.read())


def dump_menu(menu, path, header="Generated by old-tablet-dashboard. Do not edit: it is overwritten by the menu sync."):
    text = "/* %s */\nvar MENU = %s;\n" % (header, json.dumps(menu, ensure_ascii=False, indent=1))
    tmp = str(path) + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    import os
    os.replace(tmp, path)


def validate(menu):
    """Return a list of human-readable problems (empty list = valid)."""
    errors = []
    if not isinstance(menu, dict):
        return ["MENU must be an object"]
    people = menu.get("people")
    meals = menu.get("meals")
    weeks = menu.get("weeks")
    if not isinstance(people, list) or not people:
        errors.append("`people` must be a non-empty list like [{id: 'a', label: 'Alex'}]")
        people = []
    if not isinstance(meals, list) or not meals:
        errors.append("`meals` must be a non-empty list like [{id: 'lunch', label: 'Lunch', until: 16}]")
        meals = []
    if not isinstance(weeks, dict) or not weeks:
        errors.append("`weeks` must be an object with at least one week")
        weeks = {}
    person_ids = [p.get("id") for p in people if isinstance(p, dict)]
    meal_ids = [m.get("id") for m in meals if isinstance(m, dict)]
    for i, p in enumerate(people):
        if not isinstance(p, dict) or not p.get("id") or not p.get("label"):
            errors.append("people[%d] needs `id` and `label`" % i)
    last = 0
    for i, m in enumerate(meals):
        if not isinstance(m, dict) or not m.get("id") or not m.get("label"):
            errors.append("meals[%d] needs `id` and `label`" % i)
            continue
        until = m.get("until")
        if not isinstance(until, (int, float)) or not 0 < until <= 24:
            errors.append("meal `%s`: `until` must be an hour between 1 and 24" % m["id"])
        elif until < last:
            errors.append("meal `%s`: meals must be in time order (`until` %s < %s)" % (m["id"], until, last))
        else:
            last = until
    for key, w in weeks.items():
        where = "week `%s`" % key
        if not isinstance(w, dict):
            errors.append(where + " must be an object")
            continue
        if not w.get("title"):
            errors.append(where + ": missing `title`")
        start = w.get("start")
        if start is not None:
            if not isinstance(start, str) or not DATE_RE.match(start):
                errors.append(where + ": `start` must be 'YYYY-MM-DD'")
            else:
                try:
                    if datetime.date.fromisoformat(start).weekday() != 0:
                        errors.append(where + ": `start` %s is not a Monday" % start)
                except ValueError:
                    errors.append(where + ": `start` %s is not a real date" % start)
        repeat = w.get("repeat", 1)
        if not isinstance(repeat, int) or repeat < 1:
            errors.append(where + ": `repeat` must be a whole number ≥ 1")
        days = w.get("days")
        if not isinstance(days, list) or len(days) != 7:
            errors.append(where + ": `days` must have exactly 7 days (Monday first), found %s"
                          % (len(days) if isinstance(days, list) else "none"))
            continue
        for d, day in enumerate(days):
            if not isinstance(day, dict):
                errors.append("%s day %d must be an object {mealId: {personId: dish}}" % (where, d + 1))
                continue
            for meal_id, dishes in day.items():
                if meal_id not in meal_ids:
                    errors.append("%s day %d: unknown meal `%s` (not in `meals`)" % (where, d + 1, meal_id))
                elif not isinstance(dishes, dict):
                    errors.append("%s day %d meal `%s` must map person id → dish" % (where, d + 1, meal_id))
                else:
                    for pid in dishes:
                        if pid not in person_ids:
                            errors.append("%s day %d meal `%s`: unknown person `%s`" % (where, d + 1, meal_id, pid))
    shopping = menu.get("shopping", {})
    if not isinstance(shopping, dict):
        errors.append("`shopping` must map week key → {category: [products]}")
    else:
        for key, cats in shopping.items():
            if key not in weeks:
                errors.append("shopping `%s`: no week with that key" % key)
            elif not isinstance(cats, dict) or not all(isinstance(v, list) for v in cats.values()):
                errors.append("shopping `%s` must be {category: [product, ...]}" % key)
    return errors


def week_start(week):
    s = week.get("start")
    return datetime.date.fromisoformat(s) if s and DATE_RE.match(s) else None


def resolve_week(menu, date, chosen=None):
    """Same rules as the panel (docs/domain-model.md). Returns (week_key, day_index, exact) or (None, None, False)."""
    weeks = menu.get("weeks", {})
    if chosen in weeks:
        return chosen, date.weekday(), True
    dated = sorted(((week_start(w), k) for k, w in weeks.items() if week_start(w)), key=lambda x: x[0])
    for start, key in dated:
        span = 7 * int(weeks[key].get("repeat") or 1)
        diff = (date - start).days
        if 0 <= diff < span:
            return key, diff % 7, True
    if not dated:
        return None, None, False
    started = [k for s, k in dated if s <= date]
    return (started[-1] if started else dated[0][1]), date.weekday(), False
